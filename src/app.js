import {createDocumentRouter} from "./documents/documentRoutes.js";
import {criarArquivosPrivados} from './documents/arquivosPrivados.js';
import {createNeonDocumentStorage} from './documents/neonDocumentStorage.js';
import {neonAuthEnabled} from './config/neon.js';
import {createNeonUsers} from './auth/neonUsers.js';
import {createGithubUsers} from './auth/githubUsers.js';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import { uploadsDir } from './config/paths.js';
import errorHandler from './middlewares/errorHandler.js';
import notFound from './middlewares/notFound.js';
import avariaRoutes from './routes/avariaRoutes.js';
import medidaRoutes from './routes/medidaRoutes.js';
import marcaRoutes from './routes/marcaRoutes.js';
import bandaRoutes from './routes/bandaRoutes.js';
import pneuRoutes from './routes/pneuRoutes.js';
import { createAuthRouter } from './auth/authRoutes.js';
import serverlessJson from './middlewares/serverlessJson.js';
const app = express();
app.disable('x-powered-by');
app.set('query parser', 'simple');
app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' } }));
app.use(cors({ origin(origin, callback) {
  const allowed = (process.env.CORS_ORIGINS || '').split(',').map(s => s.trim()).filter(Boolean);
  callback(null, !origin || !allowed.length || allowed.includes(origin));
} }));
app.use(serverlessJson);
const jsonParser=express.json({limit:'1mb'}),pdfJsonParser=express.json({limit:'6mb'});
app.use((req,res,next)=>(/^\/api\/documentos\/[^/]+\/(pdf|fotos)$/.test(req.path)?pdfJsonParser:jsonParser)(req,res,next));
if (process.env.NODE_ENV !== 'test') app.use(morgan('dev'));
app.get('/health', (req, res) => res.json({ status: 'ok' }));
app.get('/ready', (req, res) => res.json({ status: 'ok', storage: 'json' }));
app.use('/uploads', express.static(uploadsDir, { dotfiles: 'deny', index: false }));
app.use('/images', express.static(uploadsDir, { dotfiles: 'deny', index: false }));
const usersStore=neonAuthEnabled()?createNeonUsers():createGithubUsers();
const { router: authRoutes, requireUser } = createAuthRouter(usersStore);
app.use('/api/auth', authRoutes);
app.use('/api/documentos', createDocumentRouter({requireUser,store:createNeonDocumentStorage().store,files:criarArquivosPrivados(),resolveManagers:async ids=>{if(!Array.isArray(ids))throw Object.assign(new Error('Selecione gestores válidos.'),{status:400});const {data}=await usersStore.read();return ids.map(id=>data.users.find(u=>u.id===id));}}));
app.use('/api', (req, res, next) => process.env.AUTH_REQUIRE_LOGIN === 'true' ? requireUser(req, res, next) : next());
app.use('/api/avarias', avariaRoutes);
app.use('/api/medidas', medidaRoutes);
app.use('/api/marcas', marcaRoutes);
app.use('/api/bandas-vipal', bandaRoutes);
app.use('/api/pneus-novos', pneuRoutes);
app.use('/api/bandas', bandaRoutes);
app.use('/api/pneus', pneuRoutes);
app.use(notFound);
app.use(errorHandler);
export default app;
